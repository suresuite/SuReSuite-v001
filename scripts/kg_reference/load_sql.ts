// Turn a reference dataset into ONE transaction of knowledge-graph RPC calls
// (docs/PLAN.md §29, WP 19.4). It writes nothing itself: the output is SQL that
// goes through kg_upsert_entity, record_external_evidence and
// kg_record_assertion — the same authorization, audit and natural keys as any
// other writer. Identity comes from kgResolver.ts (planLoad), and nowhere else.
//
//   deno run --allow-read scripts/kg_reference/load_sql.ts fairphone \
//     --org <uuid> --project <uuid> --actor <uuid> > fairphone.sql
//   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f fairphone.sql
import { planLoad, qualifierKey, type ReferenceDataset } from "../../supabase/functions/_shared/kgResolver.ts";
import { normalizeEntityName } from "../../supabase/functions/_shared/networkEvidence.ts";

/** Publisher groups — the independence unit — and the date each source says
 * its facts held. A company's own report is one group, however many pages. */
const PUBLISHERS: Record<string, { group: string; observed_on: (retrieved: string) => string }> = {
  "fairphone-sce-2024": { group: "Fairphone B.V.", observed_on: () => "2024-05-01" },
};
const publisher = (sourceId: string) =>
  PUBLISHERS[sourceId] ??
    (sourceId.startsWith("ema-") ? { group: "European Medicines Agency", observed_on: (r: string) => r } : null);

const q = (s: string | null | undefined) => (s == null ? "NULL" : `'${String(s).replaceAll("'", "''")}'`);
const j = (o: unknown) => `${q(JSON.stringify(o))}::jsonb`;
const arr = (xs: string[]) => (xs.length ? `ARRAY[${xs.map(q).join(",")}]::text[]` : "'{}'::text[]");

export function loadSql(name: string, org: string, project: string, actor: string, root: URL): string {
  const ds: ReferenceDataset & { label: string } = JSON.parse(Deno.readTextFileSync(new URL(`data/${name}.json`, root)));
  const sources: Array<{ id: string; url: string; sha256: string; retrieved_at: string }> =
    JSON.parse(Deno.readTextFileSync(new URL("sources.json", root))).sources;
  const src = new Map(sources.map((s) => [s.id, s]));
  const plan = planLoad(ds);
  if (plan.dangling.length) throw new Error(`${name}: dangling endpoints ${plan.dangling.join(", ")}`);
  const names = new Map(plan.entities.map((e) => [e.kg_key, e.name]));
  const out: string[] = [
    `-- GENERATED by scripts/kg_reference/load_sql.ts from data/${name}.json. ${ds.label}`,
    "BEGIN;",
    "CREATE TEMP TABLE _kg_ids (k text PRIMARY KEY, id uuid NOT NULL) ON COMMIT DROP;",
  ];
  for (const e of plan.entities) {
    // The resolver's own normalizer, applied to aliases too (single-source).
    const norm = e.aliases.map(normalizeEntityName);
    out.push(`INSERT INTO _kg_ids VALUES (${q(e.kg_key)}, public.kg_upsert_entity(${q(org)}, ${q(e.type)}, ` +
      `${q(e.kg_key)}, ${q(e.name)}, ${q(e.country)}, ${j(e.identifiers)}, ${arr(e.aliases)}, ${arr(norm)}, ` +
      `${q(name)}, ${q(actor)}));`);
  }
  for (const a of plan.assertions) {
    for (const ev of a.evidence) {
      const s = src.get(ev.source);
      const p = publisher(ev.source);
      if (!s || !p) throw new Error(`${name}: evidence source ${ev.source} is not in sources.json / PUBLISHERS`);
      const triple = { subject: { name: names.get(a.subject) }, relation: a.relation,
                       object: { name: names.get(a.object) }, quote: ev.fragment, page: ev.page,
                       qualifier: a.qualifier };
      out.push(`SELECT public.kg_record_assertion(${q(org)}, (SELECT id FROM _kg_ids WHERE k = ${q(a.subject)}), ` +
        `${q(a.relation)}, (SELECT id FROM _kg_ids WHERE k = ${q(a.object)}), ${q(qualifierKey(a.qualifier))}, ` +
        `${j(a.qualifier)}, public.record_external_evidence(${q(project)}, ${q(ev.source)}, ${q(s.url)}, ` +
        `${q(s.sha256)}, 0.9, ${j(triple)}, NULL), 'supports', ${q(p.group)}, ${q(p.observed_on(s.retrieved_at))}, ` +
        `${q(actor)});`);
    }
  }
  out.push("COMMIT;");
  return out.join("\n") + "\n";
}

if (import.meta.main) {
  const [name, ...rest] = Deno.args;
  const arg = (k: string) => rest[rest.indexOf(`--${k}`) + 1];
  if (!name || !arg("org") || !arg("project") || !arg("actor")) {
    console.error("usage: load_sql.ts <dataset> --org <uuid> --project <uuid> --actor <uuid>");
    Deno.exit(2);
  }
  console.log(loadSql(name, arg("org"), arg("project"), arg("actor"), new URL("./", import.meta.url)));
}
